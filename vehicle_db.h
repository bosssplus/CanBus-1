/* ========================================================================== */
/*   ماکرو تبدیل WMI                                                          */
/* -------------------------------------------------------------------------- */
/*   سه کاراکتر ASCII (مثلاً V, F, 3) را به یک uint32_t 24-bit تبدیل می‌کند */
/*   که با ۳ بایت اول VIN خودرو مطابقت کامل دارد.                             */
/* ========================================================================== */
#define WMI(a, b, c)  ((uint32_t)(a) << 16 | (uint32_t)(b) << 8 | (uint32_t)(c))


/* ========================================================================== */
/*   ساختار VehicleProfile                                                     */
/* ========================================================================== */
typedef struct {

  /* --- شناسه خودرو --- */
  uint32_t  wmi_code;          // WMI کد ۳ بایتی — مثال: WMI('V','F','3')

  /* --- CAN IDهای پیش‌فرض --- */
  uint16_t  can_rpm;           // CAN ID برای دور موتور (RPM)
  uint16_t  can_speed;         // CAN ID برای سرعت
  uint16_t  can_vin;           // CAN ID برای خواندن VIN از طریق UDS
  uint16_t  can_door;          // CAN ID برای وضعیت درب‌ها
  uint16_t  can_fuel;          // CAN ID برای سطح سوخت
  uint16_t  can_temp;          // CAN ID برای دمای موتور

  /* --- مشخصات خودروساز --- */
  const char* make;            // نام خودروساز (برای نمایش)

  /* --- قابلیت‌های پشتیبانی‌شده --- */
  uint32_t  capabilities;      // پرچم‌های قابلیت (OR ترکیبی)

} VehicleProfile;


/* ========================================================================== */
/*   Capability Flags — پرچم‌های قابلیت                                        */
/* -------------------------------------------------------------------------- */
/*   هر خودرو می‌تواند ترکیبی از این قابلیت‌ها را داشته باشد.                 */
/*   فرمان‌ها قبل از اجرا بررسی می‌کنند که خودروی هدف این پرچم را دارد یا نه.  */
/* ========================================================================== */
#define CAP_CAN       (1 << 0)   // قابلیت CAN Bus عادی
#define CAP_OBD2      (1 << 1)   // قابلیت OBD2 diagnostics
#define CAP_UDS       (1 << 2)   // قابلیت UDS (Unified Diagnostic Services)
#define CAP_KWP       (1 << 3)   // قابلیت KWP2000
#define CAP_RF        (1 << 4)   // قابلیت RF (433/315 MHz)
#define CAP_BLE       (1 << 5)   // قابلیت Bluetooth Low Energy
#define CAP_ROLLJAM   (1 << 6)   // قابلیت RollJam (RF جمر)
#define CAP_SNIFFER   (1 << 7)   // قابلیت Sniffer CAN巴士



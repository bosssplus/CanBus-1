/* ========================================================================== */
/*   —— تابع جستجوی خودرو بر اساس VIN ——                                       */
/* -------------------------------------------------------------------------- */
/*   ورودی:  رشته VIN به طول حداقل ۳ کاراکتر                                  */
/*   خروجی:  پوینتر به VehicleProfile یا nullptr در صورت عدم یافت              */
/* ========================================================================== */
inline const VehicleProfile* findVehicleByVIN(const char* vin) {

  /* ---- اعتبارسنجی ورودی ---- */
  if (!vin || strlen(vin) < 3) {
    return nullptr;
  }

  /* ---- استخراج WMI از ۳ بایت اول VIN ---- */
  uint32_t wmi = ((uint32_t)(vin[0]) << 16) |
                 ((uint32_t)(vin[1]) <<  8) |
                 ((uint32_t)(vin[2]));

  /* ---- جستجو در دیتابیس ---- */
  for (int i = 0; vehicle_db[i].make != nullptr; i++) {
    if (vehicle_db[i].wmi_code == wmi) {
      return &vehicle_db[i];
    }
  }

  return nullptr;  // ❌ خودرو در دیتابیس یافت نشد
}


/* ========================================================================== */
/*   —— تابع جستجوی خودرو بر اساس WMI کد ۳ بایتی ——                            */
/* -------------------------------------------------------------------------- */
/*   ورودی:  WMI کد ۳ بایتی (مانند 0x564633 برای "VF3")                       */
/*   خروجی:  پوینتر به VehicleProfile یا nullptr                               */
/* ========================================================================== */
inline const VehicleProfile* findVehicleByWMI(uint32_t wmi_3byte) {

  for (int i = 0; vehicle_db[i].make != nullptr; i++) {
    if (vehicle_db[i].wmi_code == wmi_3byte) {
      return &vehicle_db[i];
    }
  }

  return nullptr;
}


